import json, re, random
def norm(s): return s.replace('ي','ی').replace('ك','ک').replace('\u200c',' ').replace('ئ','ی').strip()
names = {norm(c['name']): c['name'] for c in json.load(open('/home/user/IronPin/assets/cities.json'))}
prov = {'26':'تهران','36':'زنجان','40':'یزد','25':'سمنان','35':'مازندران','34':'مرکزی','23':'لرستان','16':'کردستان','05':'کهگیلویه و بویراحمد','15':'خوزستان','13':'کرمانشاه','29':'کرمان','10':'ایلام','11':'هرمزگان','09':'همدان','08':'گیلان','07':'فارس','03':'چهارمحال و بختیاری','22':'بوشهر','33':'آذربایجان شرقی','01':'آذربایجان غربی','32':'اردبیل','28':'اصفهان','37':'گلستان','38':'قزوین','39':'قم','04':'سیستان و بلوچستان','41':'خراسان جنوبی','42':'خراسان رضوی','43':'خراسان شمالی','44':'البرز'}
provs = sorted(set(prov.values()))
arabic = re.compile(r'^[\u0600-\u06FF\u200c ]+$')
rows = []
for line in open('/tmp/IR.txt', encoding='utf-8'):
    f = line.rstrip('\n').split('\t')
    if f[6] != 'P': continue
    pop = int(f[14] or 0)
    code = f[7]
    if not (pop >= 3000 or code in ('PPLC','PPLA','PPLA2','PPLA3')): continue
    if f[10] not in prov: continue
    alts = [a for a in f[3].split(',') if arabic.match(a)]
    fa = ''
    for a in alts:
        if norm(a) in names: fa = names[norm(a)]; break
    matched = bool(fa)
    if not fa:
        cand = [a for a in alts if not re.search('[ةىإأؤ]', a) and 'شهرستان' not in a and 'استان' not in a]
        fa = norm(cand[0]) if cand else ''
    fa = re.sub('[\u064b-\u0652]', '', fa)
    if not fa or (not matched and pop < 20000): continue
    # GeoNames records checked and found misplaced. «اندیشه» at 35.7471,51.2774
    # is a second record of Andisheh New Town (35.6803,51.0193) put inside
    # Tehran's district 22; it made Tehran addresses resolve to Andisheh.
    if fa == 'اندیشه' and abs(float(f[4]) - 35.7471) < 0.01: continue
    rows.append((fa, float(f[4]), float(f[5]), pop, prov[f[10]], matched, f[1], code))
# one entry per (name, province): biggest population
best = {}
for r in rows:
    k = (norm(r[0]), r[4])
    if k not in best or r[3] > best[k][3]: best[k] = r
rows = sorted(best.values(), key=lambda r: -r[3])
print(len(rows), 'matched', sum(r[5] for r in rows))
for r in rows[:25]: print(r[0], r[4], r[3], r[6])
random.seed(3)
for r in random.sample(rows, 25): print('  ', r[0], '|', r[4], r[3], r[6], r[5])
with open('/home/user/IronPin/lib/domain/geo_cities.g.dart', 'w', encoding='utf-8') as o:
    o.write('// GENERATED by tool/gen_geo.py from GeoNames (https://www.geonames.org, CC BY 4.0).\n')
    o.write('// Populated places of Iran: name|latitude|longitude|population|province index.\n')
    o.write('// Do not edit by hand.\n\n')
    o.write('const List<String> geoProvinces = [\n' + ''.join(f"  '{p}',\n" for p in provs) + '];\n\n')
    o.write("const String geoCityTable = '''\n")
    for r in rows:
        o.write(f"{r[0]}|{r[1]:.4f}|{r[2]:.4f}|{r[3]}|{provs.index(r[4])}\n")
    o.write("''';\n")
